#!/usr/bin/env python3
"""Seeded bounded known-negative mutations of the published v0 profile.

This is a reproducible adversarial regression harness, not exhaustive fuzzing or
an independent security audit. Inputs are committed synthetic conformance data.
"""
import argparse
import base64
from collections import Counter
from dataclasses import replace
import json
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[2]


def require(condition):
    if not condition:
        raise AssertionError("qualification invariant failed")


class CountClaims:
    def __init__(self):
        self.calls = 0
    def claim(self, *args, **kwargs):
        self.calls += 1
        return True


def qualify(iterations, seed):
    from appguard.types import RequestInput, SignatureParameters, KeyRecord, VerificationError
    from appguard.verify import verify_request
    from appguard.wire import parse_signatures
    if type(iterations) is not int or not 1 <= iterations <= 50000 or type(seed) is not int:
        raise ValueError('bounded run required')
    case = json.loads((ROOT / 'conformance/v0/requests.json').read_text())[0]
    request = RequestInput(case['request']['method'], case['request']['target'],
                           tuple(tuple(pair) for pair in case['request']['headers']),
                           base64.b64decode(case['request']['body_b64']))
    parameters = SignatureParameters(**case['parameters'])
    signature = base64.b64decode(case['signature_b64'])
    key = KeyRecord(**{**case['key'], 'public_key_pem': case['key']['public_key_pem'].encode()})
    context = {**case['context'], 'key': key}
    baseline = CountClaims()
    require(verify_request(request, parameters, signature, **context, replay=baseline).code == 'VERIFIED')
    require(baseline.calls == 1)
    wire = json.loads((ROOT / 'conformance/v0/http.json').read_text())[0]
    headers = tuple(tuple(pair) for pair in wire['headers'])
    require(parse_signatures(headers).signature == base64.b64decode(wire['expected']['signature_b64']))
    rng = random.Random(seed)
    core_reasons, wire_reasons = Counter(), Counter()
    negatives = CountClaims()
    for index in range(iterations):
        req, params, sig, kwargs = request, parameters, signature, dict(context)
        mode = index % 8
        if mode == 0:
            req = replace(request, body=request.body + rng.randbytes(rng.randrange(1, 33)))
        elif mode == 1:
            req = replace(request, target=request.target + '&mutated=' + format(rng.getrandbits(64), '016x'))
        elif mode == 2:
            raw = bytearray(signature)
            raw[rng.randrange(64)] ^= 1 << rng.randrange(8)
            sig = bytes(raw)
        elif mode == 3:
            kwargs['key'] = replace(key, revoked=True)
        elif mode == 4:
            kwargs['subject'] = 'other-' + str(rng.getrandbits(32))
        elif mode == 5:
            params = replace(parameters, nonce=parameters.nonce + '=')
        elif mode == 6:
            kwargs['now'] = parameters.expires + rng.randrange(30)
        else:
            req = replace(request, headers=request.headers + (request.headers[0],))
        try:
            verify_request(req, params, sig, **kwargs, replay=negatives)
        except VerificationError as error:
            if error.code not in {'INVALID_REQUEST', 'INVALID_SIGNATURE', 'DIGEST_MISMATCH', 'KEY_REJECTED', 'INVALID_TIME'}:
                raise AssertionError('unexpected error code') from None
            core_reasons[error.code] += 1
        else:
            raise AssertionError('known-negative core input accepted')
        # Every transformation below violates the fixed wire grammar, regardless
        # of the generated byte, spelling or amount of additional metadata.
        varied = list(headers)
        mode = index % 5
        if mode == 0:
            varied.append(('SIGNATURE', dict((n.lower(), v) for n, v in headers)['signature']))
        elif mode == 1:
            varied = [(n, ' ' * rng.randrange(1, 4) + v if n.lower() == 'signature-input' else v) for n, v in varied]
        elif mode == 2:
            varied = [(n, v + ';extra="' + str(rng.getrandbits(32)) + '"' if n.lower() == 'signature-input' else v) for n, v in varied]
        elif mode == 3:
            varied = [(n, v + chr(rng.randrange(1, 32)) if n.lower() == 'signature' else v) for n, v in varied]
        else:
            varied.extend(('x-qualification-' + str(i), 'a') for i in range(65 + rng.randrange(20)))
        try:
            parse_signatures(tuple(varied))
        except VerificationError as error:
            if error.code != 'INVALID_REQUEST':
                raise AssertionError('unexpected wire error code') from None
            wire_reasons[error.code] += 1
        else:
            raise AssertionError('known-negative wire input accepted')
    require(negatives.calls == 0)
    return {'status': 'passed', 'seed': seed, 'baseline_verified': True, 'core_mutations': iterations,
            'wire_mutations': iterations, 'unexpected_acceptances': 0, 'negative_replay_claims': negatives.calls,
            'core_reasons': dict(core_reasons), 'wire_reasons': dict(wire_reasons),
            'scope': 'Python reference core and HTTP wire parser; deterministic known-invalid classes, not coverage-guided fuzzing'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--iterations', type=int, default=2000)
    parser.add_argument('--seed', type=int, default=20261022)
    args = parser.parse_args()
    try:
        report = qualify(args.iterations, args.seed)
    except Exception:
        print('{"status":"failed","code":"ADVERSARIAL_QUALIFICATION_FAILED"}', file=sys.stderr)
        return 1
    print(json.dumps(report, sort_keys=True, separators=(',', ':')))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
